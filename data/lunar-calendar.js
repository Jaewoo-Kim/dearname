// 기준일: 1900년 1월 1일
const _LUNAR_BASE = new Date(Date.UTC(1900, 0, 1));

function _dateToAbs(dateStr) {
  const [y,m,d] = dateStr.split('-').map(Number);
  return Math.round((new Date(Date.UTC(y, m-1, d)) - _LUNAR_BASE) / 86400000);
}

function _absToDateStr(abs) {
  const d = new Date(_LUNAR_BASE.getTime() + abs * 86400000);
  return `${d.getUTCFullYear()}-${String(d.getUTCMonth()+1).padStart(2,'0')}-${String(d.getUTCDate()).padStart(2,'0')}`;
}

/**
 * 음력 → 양력 변환
 * @param {number} ly 음력 연도
 * @param {number} lm 음력 월
 * @param {number} ld 음력 일
 * @param {boolean} isLeap 윤달 여부
 * @returns {string|null} 'YYYY-MM-DD' 또는 null
 */
function lunarToSolar(ly, lm, ld, isLeap) {
  const data = LUNAR_DB[ly];
  if (!data) return null;
  
  const {leap, starts} = data;
  let idx;
  
  if (isLeap) {
    if (leap !== lm) return null; // 이 달에 윤달 없음
    idx = lm; // 윤달 인덱스: 해당 달 바로 다음 (0-based로 lm번째)
  } else if (leap > 0 && lm > leap) {
    idx = lm; // 윤달 이후: 일반 달보다 인덱스 1 증가
  } else {
    idx = lm - 1; // 정월=0
  }
  
  if (idx >= starts.length) return null;
  const monthStart = starts[idx];
  
  // 다음달 시작일 (경계값)
  let nextStart;
  if (idx + 1 < starts.length) {
    nextStart = starts[idx + 1];
  } else {
    const nextYearData = LUNAR_DB[ly + 1];
    nextStart = nextYearData ? nextYearData.starts[0] : null;
  }
  if (!nextStart) return null;
  
  const monthLen = nextStart - monthStart;
  if (ld < 1 || ld > monthLen) return null;
  
  return _absToDateStr(monthStart + ld - 1);
}

/**
 * 입력 폼용: 날짜 문자열 + 달력 타입 → 양력 날짜 문자열
 * @param {string} dateStr 'YYYY-MM-DD'
 * @param {string} calType 'solar' | 'lunar' | 'leap'
 * @returns {string} 양력 'YYYY-MM-DD'
 */
function normalizeToSolar(dateStr, calType) {
  if (!dateStr) return '';
  if (calType === 'solar') return dateStr;
  
  const [y, m, d] = dateStr.split('-').map(Number);
  const isLeap = (calType === 'leap');
  const result = lunarToSolar(y, m, d, isLeap);
  
  if (!result) {
    console.warn(`음력 변환 실패: ${dateStr} (${calType})`);
    return dateStr;
  }
  return result;
}
